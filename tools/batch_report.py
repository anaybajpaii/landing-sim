import argparse
import math
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

NAMES = {
    0: "success",
    1: "timeout",
    2: "off_platform",
    3: "hard_landing",
    4: "relative_speed",
    5: "tilt",
}

REQUIRED = [
    "run",
    "plat_x0",
    "plat_y0",
    "outcome",
    "touch_time",
    "vertical_speed",
    "offset",
]


def wilson_lower(successes, runs):
    if runs <= 0:
        return 0.0
    z = 1.96
    p = successes / runs
    z2 = z * z
    centre = p + z2 / (2.0 * runs)
    margin = z * math.sqrt(p * (1.0 - p) / runs + z2 / (4.0 * runs * runs))
    return max(0.0, (centre - margin) / (1.0 + z2 / runs))


def main():
    parser = argparse.ArgumentParser(description="Plot and summarise a landing-sim batch CSV.")
    parser.add_argument("csv", type=Path)
    parser.add_argument("--seed", default="unspecified")
    parser.add_argument("--out-dir", type=Path, default=Path("docs"))
    args = parser.parse_args()

    df = pd.read_csv(args.csv)
    missing = [c for c in REQUIRED if c not in df.columns]
    if missing:
        raise SystemExit(f"batch csv is missing columns: {missing}")

    runs = len(df)
    if runs == 0:
        raise SystemExit("batch csv has no rows")

    outcome = df["outcome"].astype(int)
    success = outcome == 0
    landed = int(success.sum())
    rate = landed / runs
    lower = wilson_lower(landed, runs)
    counts = {code: int((outcome == code).sum()) for code in NAMES}

    fig, axes = plt.subplots(2, 2, figsize=(10, 9))

    ax = axes[0, 0]
    ax.scatter(df.loc[success, "plat_x0"], df.loc[success, "plat_y0"], marker="o",
               label=f"landed ({landed})")
    ax.scatter(df.loc[~success, "plat_x0"], df.loc[~success, "plat_y0"], marker="x",
               label=f"failed ({runs - landed})")
    ax.scatter([0.0], [0.0], marker="*", s=150, label="quad start")
    ax.set_aspect("equal")
    ax.set_xlabel("platform start x [m]")
    ax.set_ylabel("platform start y [m]")
    ax.set_title("Platform start positions")
    ax.legend(loc="best")
    ax.grid(True, alpha=0.3)

    ax = axes[0, 1]
    ax.bar(list(NAMES.values()), [counts[c] for c in NAMES])
    ax.set_ylabel("runs")
    ax.set_title("Outcomes")
    ax.tick_params(axis="x", labelrotation=30)
    ax.grid(True, axis="y", alpha=0.3)

    ax = axes[1, 0]
    if landed > 0:
        ax.hist(df.loc[success, "touch_time"], bins=10)
    else:
        ax.text(0.5, 0.5, "no successful landings", ha="center", va="center",
                transform=ax.transAxes)
    ax.set_xlabel("time of touchdown [s]")
    ax.set_ylabel("runs")
    ax.set_title("Touchdown time (successful runs)")
    ax.grid(True, alpha=0.3)

    ax = axes[1, 1]
    if landed > 0:
        ax.scatter(df.loc[success, "offset"], df.loc[success, "vertical_speed"])
        ax.axhline(0.5, linestyle="--", label="limit 0.5 m/s")
        ax.legend(loc="best")
    else:
        ax.text(0.5, 0.5, "no successful landings", ha="center", va="center",
                transform=ax.transAxes)
    ax.set_xlabel("offset from platform centre [m]")
    ax.set_ylabel("descent speed at contact [m/s]")
    ax.set_title("Touchdown quality (successful runs)")
    ax.grid(True, alpha=0.3)

    fig.tight_layout()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    png = args.out_dir / "batch_results.png"
    fig.savefig(png, dpi=150)

    lines = [
        "# Batch results",
        "",
        f"Seed: {args.seed}",
        "",
        f"Landed: {landed} of {runs} ({100.0 * rate:.1f}%)",
        "",
        f"95% Wilson lower bound: {100.0 * lower:.1f}%",
        "",
        f"Target of 90% landed: {'met' if rate >= 0.9 else 'not met'}",
        "",
        "| outcome | runs |",
        "| --- | --- |",
    ]
    for code, name in NAMES.items():
        lines.append(f"| {name} | {counts[code]} |")
    if landed > 0:
        ok = df[success]
        lines += [
            "",
            f"Successful landings: mean touchdown time {ok['touch_time'].mean():.1f} s, "
            f"worst offset {ok['offset'].max():.2f} m, "
            f"worst descent speed {ok['vertical_speed'].max():.2f} m/s",
        ]
    failed = df[~success]
    if len(failed) > 0:
        lines += ["", "Failed runs: " + ", ".join(str(int(r)) for r in failed["run"])]
    lines += [
        "",
        "Generated by tools/batch_report.py from the output of "
        "`landing_sim --scenario batch`.",
        "",
        "![batch results](batch_results.png)",
        "",
    ]
    md = args.out_dir / "batch_results.md"
    md.write_text("\n".join(lines), encoding="utf-8")

    print(f"{landed}/{runs} landed ({100.0 * rate:.1f}%), 95% lower bound {100.0 * lower:.1f}%")
    print(f"saved {png}")
    print(f"saved {md}")


if __name__ == "__main__":
    main()